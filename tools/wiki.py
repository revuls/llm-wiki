# --------------------------------------------------------------------------- small utils

def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def write(path, text):
    d = os.path.dirname(path)
    if d:
        os.makedirs(d, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def posix(path):
    return path.replace(os.sep, "/")


def today():
    return dt.date.today().isoformat()


def git(root, *args, check=False):
    if not shutil.which("git"):
        return None
    r = subprocess.run(["git", "-C", root] + list(args), capture_output=True, text=True)
    if check and r.returncode != 0:
        sys.exit("error: git %s failed: %s" % (" ".join(args), r.stderr.strip()))
    return r.stdout.strip() if r.returncode == 0 else None


# --------------------------------------------------------------------------- yaml subset

def parse_scalar(value):
    value = value.strip()
    if value.startswith("[") and value.endswith("]"):
        inner = value[1:-1].strip()
        return [parse_scalar(v) for v in inner.split(",")] if inner else []
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    if value.lower() in ("true", "false"):
        return value.lower() == "true"
    if re.fullmatch(r"-?\d+", value):
        return int(value)
    return value


def strip_comment(line):
    in_quote = None
    for i, ch in enumerate(line):
        if ch in "\"'":
            in_quote = None if in_quote == ch else (in_quote or ch)
        elif ch == "#" and not in_quote and (i == 0 or line[i - 1].isspace()):
            return line[:i].rstrip()
    return line.rstrip()


def load_yaml(text):
    """Minimal YAML subset: nested maps, lists of scalars/maps, folded scalars, inline lists."""
    try:
        import yaml  # type: ignore
        return yaml.safe_load(text) or {}
    except ImportError:
        pass
    lines = [strip_comment(l) for l in text.splitlines()]
    lines = [l for l in lines if l.strip()]
    pos = 0

    def indent(l):
        return len(l) - len(l.lstrip(" "))

    def parse_block(level):
        nonlocal pos
        if pos < len(lines) and lines[pos].lstrip().startswith("- "):
            result = []
            while pos < len(lines) and indent(lines[pos]) == level and lines[pos].lstrip().startswith("- "):
                item = lines[pos].lstrip()[2:]
                if re.match(r"^[\w-]+:( |$)", item):
                    lines[pos] = " " * (level + 2) + item
                    result.append(parse_block(level + 2))
                else:
                    result.append(parse_scalar(item))
                    pos += 1
            return result
        result = {}
        while pos < len(lines) and indent(lines[pos]) == level:
            key, _, rest = lines[pos].strip().partition(":")
            rest = rest.strip()
            pos += 1
            if rest in (">", "|", ">-", "|-"):
                parts = []
                while pos < len(lines) and indent(lines[pos]) > level:
                    parts.append(lines[pos].strip())
                    pos += 1
                result[key] = " ".join(parts)
            elif rest:
                result[key] = parse_scalar(rest)
            elif pos < len(lines) and indent(lines[pos]) > level:
                result[key] = parse_block(indent(lines[pos]))
            elif pos < len(lines) and indent(lines[pos]) == level and lines[pos].lstrip().startswith("- "):
                result[key] = parse_block(level)
            else:
                result[key] = None
        return result

    return parse_block(0) if lines else {}


def split_frontmatter(text):
    if not text.startswith("---"):
        return None, text
    end = text.find("\n---", 3)
    if end == -1:
        return None, text
    raw = text[3:end].strip("\n")
    body = text[end + 4:].lstrip("\n")
    try:
        fm = load_yaml(raw)
    except Exception:
        fm = {"__invalid__": True}
    return (fm if isinstance(fm, dict) else {"__invalid__": True}), body


def load_config(root):
    path = os.path.join(root, "wiki.config.yaml")
    return (load_yaml(read(path)) or {}) if os.path.exists(path) else {}


# --------------------------------------------------------------------------- model

def clean_for_links(text):
    text = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    text = re.sub(r"```.*?```", "", text, flags=re.S)
    return re.sub(r"`[^`\n]*`", "", text)


class Page:
    def __init__(self, root, path):
        self.path = path
        self.rel = posix(os.path.relpath(path, root))
        self.slug = os.path.splitext(os.path.basename(path))[0]
        self.text = read(path)
        self.fm, self.body = split_frontmatter(self.text)
        links = [l.strip() for l in WIKILINK_RE.findall(clean_for_links(self.body))]
        self.links = [l for l in links if ":" not in l]
        self.xlinks = [l for l in links if ":" in l]
        parts = self.rel.split("/")
        self.section = "overview" if len(parts) == 2 else ("meta" if parts[1] == "_meta" else parts[1])

    def get(self, key, default=None):
        return (self.fm or {}).get(key, default)

    @property
    def title(self):
        if self.get("title"):
            return str(self.get("title"))
        m = re.search(r"^# (.+)$", self.body, re.M)
        return m.group(1).strip() if m else self.slug

    @property
    def type(self):
        return self.get("type")

    @property
    def special(self):
        return self.rel in ("wiki/index.md", "wiki/log.md")

    @property
    def generated_index(self):
        return self.rel.startswith("wiki/_meta/index-")

    @property
    def source_slugs(self):
        return sorted(set(l for l in self.links if l.startswith("src-")))


class Wiki:
    def __init__(self, root):
        self.root = os.path.abspath(root)
        self.wiki_dir = os.path.join(self.root, "wiki")
        self.raw_dir = os.path.join(self.root, "raw")
        if not os.path.isdir(self.wiki_dir):
            sys.exit("error: no wiki/ directory under %s" % self.root)
        self.config = load_config(self.root)
        self.pages = []
        for dirpath, dirnames, filenames in os.walk(self.wiki_dir):
            dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
            for fn in sorted(filenames):
                if fn.endswith(".md"):
                    self.pages.append(Page(self.root, os.path.join(dirpath, fn)))
        self.by_slug = defaultdict(list)
        for p in self.pages:
            self.by_slug[p.slug].append(p)

    @property
    def id(self):
        return self.config.get("id")

    def page(self, slug):
        found = self.by_slug.get(slug)
        return found[0] if found else None

    def content_pages(self):
        return [p for p in self.pages if not p.special and not p.generated_index]

    def inbound(self):
        inbound = defaultdict(set)
        for p in self.content_pages():
            for target in p.links:
                inbound[target].add(p.slug)
        return inbound


# --------------------------------------------------------------------------- linked wikis

def discover_wikis(wiki):
    """Return ({id: info}, problems). Sources: sibling folders + linked_wikis in config."""
    found, problems = {}, []
    exclude = set(wiki.config.get("exclude_wikis") or [])

    def add(path, origin, fallback=None):
        path = os.path.normpath(path)
        available = os.path.isdir(os.path.join(path, "wiki"))
        cfg = load_config(path) if available else {}
        if cfg.get("template"):
            return
        info = dict(fallback or {})
        info.update({k: v for k, v in cfg.items() if k in ("id", "name", "description", "scope")})
        wid = info.get("id")
        if not wid or wid == wiki.id or wid in exclude:
            return
        if wid in found and os.path.normpath(found[wid]["path"]) != path:
            problems.append("duplicate wiki id '%s': %s and %s" % (wid, found[wid]["path"], path))
            return
        scope = info.get("scope")
        if isinstance(scope, dict):
            scope = "; ".join(str(s) for s in (scope.get("in") or []))
        info.update({"path": path, "origin": origin, "available": available, "scope": scope or ""})
        found[wid] = info

    if wiki.config.get("link_siblings", True):
        parent = os.path.dirname(wiki.root)
        for name in sorted(os.listdir(parent)):
            p = os.path.join(parent, name)
            if p != wiki.root and os.path.isfile(os.path.join(p, "wiki.config.yaml")):
                add(p, "sibling")
    for entry in wiki.config.get("linked_wikis") or []:
        if isinstance(entry, dict) and entry.get("path"):
            add(os.path.join(wiki.root, str(entry["path"])), "config", entry)
    return found, problems


# --------------------------------------------------------------------------- index

def section_title(key):
    return {"overview": "Overview", "meta": "Meta"}.get(key, key.replace("-", " ").title())


def index_entry(p):
    summary = str(p.get("summary") or "_(no summary)_")
    updated = p.get("updated") or "?"
    if p.type == "source":
        return "- [[%s]] — %s (updated %s)" % (p.slug, summary, updated)
    n = len(p.source_slugs)
    if p.type in NEEDS_SOURCES:
        return "- [[%s]] — %s (%d source%s, updated %s)" % (p.slug, summary, n, "" if n == 1 else "s", updated)
    return "- [[%s]] — %s" % (p.slug, summary)


def build_index(wiki):
    """Return {relative path: content} for wiki/index.md and any split index pages."""
    sections = defaultdict(list)
    for p in wiki.content_pages():
        sections[p.section].append(p)
    others = sorted(k for k in sections if k not in SECTION_ORDER + SECTION_LAST)
    order = [k for k in SECTION_ORDER + others + SECTION_LAST if k in sections or k in DEFAULT_CATEGORIES]
    for key, pages in sections.items():
        if key == "sources":
            pages.sort(key=lambda p: p.slug, reverse=True)
        else:
            pages.sort(key=lambda p: (p.section != "overview", p.title.lower()))

    total = sum(len(v) for k, v in sections.items() if k not in ("overview", "meta"))
    split_after = int((wiki.config.get("index") or {}).get("split_after") or 300)
    split = total > split_after
    head = ("# Index\n\n<!-- %s index — do not edit by hand. Set `summary:` in each page's "
            "frontmatter and run `python3 tools/wiki.py index`. -->\n\n"
            "Catalog of every page in this wiki (%d content pages). Read it first when answering a question.\n"
            % (GENERATED, total))
    out, parts = {}, [head]
    for key in order:
        pages = sections.get(key, [])
        parts.append("\n## %s\n" % section_title(key))
        if split and key not in ("overview", "meta"):
            slug = "index-" + key
            parts.append("- [[%s]] — %s (%d pages)\n" % (slug, section_title(key), len(pages)))
            updated = max([str(p.get("updated") or "") for p in pages] or [""]) or today()
            out["wiki/_meta/%s.md" % slug] = (
                "---\ntitle: Index — %s\ntype: meta\nsummary: Catalog of %s pages (generated).\nupdated: %s\n---\n\n"
                "# Index — %s\n\n<!-- %s index -->\n\n%s\n"
                % (section_title(key), key, updated, section_title(key), GENERATED,
                   "\n".join(index_entry(p) for p in pages) or "_None yet._"))
        else:
            parts.append(("\n".join(index_entry(p) for p in pages) or "_None yet._") + "\n")
    out["wiki/index.md"] = "".join(parts)
    return out


def stale_index_files(wiki, expected):
    meta = os.path.join(wiki.wiki_dir, "_meta")
    if not os.path.isdir(meta):
        return []
    return [posix(os.path.join("wiki", "_meta", f)) for f in os.listdir(meta)
            if f.startswith("index-") and f.endswith(".md") and posix(os.path.join("wiki", "_meta", f)) not in expected]


def index_diff(wiki):
    expected = build_index(wiki)
    changed = [rel for rel, text in expected.items()
               if not os.path.exists(os.path.join(wiki.root, rel)) or read(os.path.join(wiki.root, rel)) != text]
    return expected, changed, stale_index_files(wiki, expected)


def cmd_index(wiki, args):
    expected, changed, stale = index_diff(wiki)
    if args.check:
        for rel in changed + stale:
            print("OUTDATED %s" % rel)
        if changed or stale:
            print("Index is out of date. Run: python3 tools/wiki.py index")
            return 1
        if not args.quiet:
            print("index is up to date")
        return 0
    for rel in changed:
        write(os.path.join(wiki.root, rel), expected[rel])
    for rel in stale:
        os.remove(os.path.join(wiki.root, rel))
    if not args.quiet:
        print("index: %d file(s) written, %d removed" % (len(changed), len(stale)) if changed or stale else "index is up to date")
    return 0


# --------------------------------------------------------------------------- search

def tokenize(text):
    return re.findall(r"[a-z0-9]+", text.lower())


def cmd_search(wiki, args):
    terms = [t for t in tokenize(args.query) if len(t) > 1]
    if not terms:
        sys.exit("error: empty query")
    docs = {}
    for p in wiki.content_pages():
        aliases = " ".join(str(a) for a in (p.get("aliases") or []))
        head = "%s %s %s %s" % (p.title, p.slug, aliases, p.get("summary") or "")
        docs[p.slug] = (p, Counter(tokenize(p.body)), set(tokenize(head)))
    n = len(docs) or 1
    df = Counter()
    for _, counts, head in docs.values():
        for t in set(terms):
            if counts[t] or t in head:
                df[t] += 1
    results = []
    for p, counts, head in docs.values():
        score, matched = 0.0, 0
        for t in terms:
            if counts[t] or t in head:
                matched += 1
                score += math.log(1 + n / (1 + df[t])) * (math.log(1 + counts[t]) + (3.0 if t in head else 0.0))
        if matched:
            results.append((score * matched / len(terms), p))
    results.sort(key=lambda r: -r[0])
    for score, p in results[: args.limit]:
        print("%6.2f  [[%s]]  %s  (%s)" % (score, p.slug, p.title, p.rel))
        if p.get("summary"):
            print("        %s" % str(p.get("summary"))[:160])
    if not results:
        print("no matches")


# --------------------------------------------------------------------------- pending raw

def norm_raw(value):
    v = posix(str(value)).strip()
    while v.startswith("../") or v.startswith("./"):
        v = v.split("/", 1)[1]
    return v


def pending_raw(wiki):
    if not os.path.isdir(wiki.raw_dir):
        return []
    sources = [p for p in wiki.pages if p.type == "source"]
    declared = set()
    for p in sources:
        raw = p.get("raw")
        for v in (raw if isinstance(raw, list) else [raw]):
            if v:
                declared.add(norm_raw(v))
    corpus = "\n".join(p.text for p in sources)
    pending = []
    for dirpath, dirnames, filenames in os.walk(wiki.raw_dir):
        rel_dir = posix(os.path.relpath(dirpath, wiki.raw_dir))
        if rel_dir.split("/")[0] == "assets":
            dirnames[:] = []
            continue
        dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
        for fn in sorted(filenames):
            if fn.startswith("."):
                continue
            rel = posix(os.path.relpath(os.path.join(dirpath, fn), wiki.root))
            if rel not in declared and fn not in corpus:
                pending.append(rel)
    return pending


def cmd_pending(wiki, args):
    files = pending_raw(wiki)
    print("\n".join(files) if files else "nothing pending")


# --------------------------------------------------------------------------- lint

def cmd_lint(wiki, args):
    errors, warnings, infos = [], [], []
    inbound = wiki.inbound()

    for slug, pages in wiki.by_slug.items():
        if len(pages) > 1:
            errors.append("duplicate slug '%s': %s" % (slug, ", ".join(p.rel for p in pages)))

    missing = defaultdict(set)
    for p in wiki.content_pages():
        if not SLUG_RE.match(p.slug):
            warnings.append("%s: file name is not kebab-case" % p.rel)
        for target in p.links:
            if not wiki.page(target):
                missing[target].add(p.slug)
        if p.fm is None:
            errors.append("%s: missing frontmatter" % p.rel)
            continue
        if p.fm.get("__invalid__"):
            errors.append("%s: unparseable frontmatter" % p.rel)
            continue
        for field in REQUIRED_FIELDS:
            if not p.get(field):
                errors.append("%s: frontmatter missing '%s'" % (p.rel, field))
        if not p.get("summary"):
            warnings.append("%s: frontmatter missing 'summary' (used by the index)" % p.rel)
        if p.type and p.type not in VALID_TYPES:
            errors.append("%s: unknown type '%s'" % (p.rel, p.type))
        if p.type == "source" and not p.get("raw"):
            warnings.append("%s: source page without 'raw:' path" % p.rel)
        if p.type in NEEDS_SOURCES and not p.source_slugs:
            warnings.append("%s: no source citations ([[src-…]])" % p.rel)
        if p.section not in ("overview", "meta") and not inbound.get(p.slug):
            warnings.append("%s: orphan (no inbound links from other pages)" % p.rel)

    for target, sources in sorted(missing.items()):
        warnings.append("missing page [[%s]] linked from %s" % (target, ", ".join(sorted(sources))))

    known, problems = discover_wikis(wiki)
    errors.extend(problems)
    for p in wiki.pages:
        for x in p.xlinks:
            wid = x.split(":", 1)[0]
            if wid not in known:
                errors.append("%s: [[%s]] refers to unknown wiki '%s'" % (p.rel, x, wid))

    log = os.path.join(wiki.wiki_dir, "log.md")
    if os.path.exists(log):
        for i, line in enumerate(read(log).splitlines(), 1):
            if line.startswith("## ") and not LOG_ENTRY_RE.match(line):
                warnings.append("wiki/log.md:%d: malformed entry header" % i)

    _, changed, stale = index_diff(wiki)
    if changed or stale:
        warnings.append("index is out of date (run: python3 tools/wiki.py index)")

    if not args.quick:
        days = int((wiki.config.get("lint") or {}).get("stale_after_days") or 180)
        for p in wiki.content_pages():
            try:
                age = (dt.date.today() - dt.date.fromisoformat(str(p.get("updated")))).days
            except ValueError:
                continue
            if age > days and p.type != "meta":
                infos.append("%s: not updated for %d days" % (p.rel, age))
            if p.get("status") == "disputed":
                infos.append("%s: status disputed" % p.rel)
        for f in pending_raw(wiki):
            infos.append("raw file not ingested: %s" % f)

    for label, items in (("ERROR", errors), ("WARN", warnings), ("INFO", infos)):
        for item in items:
            print("%-5s %s" % (label, item))
    print("\n%d errors, %d warnings, %d info (%d pages)" % (len(errors), len(warnings), len(infos), len(wiki.content_pages())))
    return 1 if errors else 0


# --------------------------------------------------------------------------- log

def cmd_log(wiki, args):
    path = os.path.join(wiki.wiki_dir, "log.md")
    if args.action and args.action[0] == "add":
        if len(args.action) != 3 or args.action[1] not in LOG_OPS:
            sys.exit("usage: wiki.py log add {%s} \"Title\" -m \"bullet\" ..." % ",".join(LOG_OPS))
        entry = "\n## [%s] %s | %s\n" % (today(), args.action[1], args.action[2])
        entry += "".join("- %s\n" % m for m in args.message or [])
        text = read(path).rstrip("\n") + "\n" + entry
        write(path, text)
        print(entry.strip())
        return 0
    if args.action:
        sys.exit("usage: wiki.py log [-n N] | log add OP TITLE -m ...")
    entries = [l for l in read(path).splitlines() if l.startswith("## [")]
    print("\n".join(entries[-args.n:]) if entries else "log is empty")
    return 0


