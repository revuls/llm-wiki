#!/usr/bin/env python3
"""LLM Wiki helper CLI. Standard library only (Python 3.8+). Works on Windows, macOS, Linux.

Everyday:
  status                 Overview: pages, pending sources, recent log, linked wikis, health
  search <query>         Rank wiki pages by relevance
  index [--check]        Regenerate wiki/index.md from page frontmatter
  lint [--quick]         Mechanical health checks (exit 1 on errors)
  pending                Raw files not yet ingested (no source page with `raw:` pointing to them)
  log [-n N]             Show recent log entries
  log add OP TITLE -m …  Append a well-formed log entry

Cross-wiki:
  wikis                  Linked wikis (auto-discovered siblings + wiki.config.yaml)
  xlinks                 Verify [[wiki-id:slug]] references

Framework:
  sync [--check]         Regenerate tool-specific agent files from .agents/
  upgrade [--from PATH]  Update framework files from the template repo
  new <dir> [...]        Create a new wiki from this framework
  init [...]             Turn a fresh "Use this template" copy into a wiki, in place

Use --root to operate on another wiki (default: the repo containing this script).
"""

