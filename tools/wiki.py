def cmd_status(wiki, args):
    cfg = wiki.config
    print("%s (id: %s)%s" % (cfg.get("name", "?"), cfg.get("id", "?"), "  [TEMPLATE]" if cfg.get("template") else ""))
    if cfg.get("description"):
        print("  %s" % cfg["description"])
    types = Counter(p.type or "?" for p in wiki.content_pages())
    print("\nPages: %d  (%s)" % (sum(types.values()), ", ".join("%s %d" % kv for kv in sorted(types.items()))))
    hubs = sorted(((len(v), k) for k, v in wiki.inbound().items() if wiki.page(k)), reverse=True)[:5]
    if hubs:
        print("Hubs: %s" % ", ".join("[[%s]] (%d)" % (k, c) for c, k in hubs))
    pending = pending_raw(wiki)
    print("\nPending raw files: %d" % len(pending))
    for f in pending[:10]:
        print("  %s" % f)
    entries = [l for l in read(os.path.join(wiki.wiki_dir, "log.md")).splitlines() if l.startswith("## [")]
    print("\nRecent log:")
    for e in entries[-5:]:
        print("  %s" % e[3:])
    known, problems = discover_wikis(wiki)
    print("\nLinked wikis: %s" % (", ".join("%s%s" % (k, "" if v["available"] else " (missing)") for k, v in known.items()) or "none"))
    health = []
    _, changed, stale = index_diff(wiki)
    if changed or stale:
        health.append("index out of date → python3 tools/wiki.py index")
    if sync_plan(wiki.root)[1:] != ([], []):
        health.append("agent files out of date → python3 tools/wiki.py sync")
    if os.path.isdir(os.path.join(wiki.root, ".git")) and git(wiki.root, "config", "core.hooksPath") != ".githooks":
        health.append("git hooks not enabled → git config core.hooksPath .githooks")
    health.extend(problems)
    print("\nHealth: %s" % ("OK" if not health else ""))
    for h in health:
        print("  ! %s" % h)
    lock = os.path.join(wiki.root, ".agents", "framework.lock")
    if os.path.exists(lock):
        info = json.loads(read(lock))
        print("\nFramework: %s @ %s (%s)" % (info.get("repo"), (info.get("commit") or "?")[:10], info.get("upgraded")))
    return 0


def cmd_wikis(wiki, args):
    known, problems = discover_wikis(wiki)
    if args.json:
        print(json.dumps(known, indent=2, ensure_ascii=False))
        return 0
    if not known:
        print("no linked wikis (siblings with wiki.config.yaml are discovered automatically)")
    for wid, w in known.items():
        print("%-18s %-28s %s%s" % (wid, w.get("name", ""), posix(os.path.relpath(w["path"], wiki.root)),
                                    "" if w["available"] else "  [NOT FOUND]"))
        if w.get("scope"):
            print("%-18s scope: %s" % ("", w["scope"]))
    for p in problems:
        print("ERROR %s" % p)
    return 1 if problems else 0


def cmd_xlinks(wiki, args):
    known, problems = discover_wikis(wiki)
    status, cache, count = 0, {}, 0
    for p in wiki.pages:
        for x in p.xlinks:
            count += 1
            wid, slug = x.split(":", 1)
            w = known.get(wid)
            if not w:
                print("ERROR %s: [[%s]] unknown wiki id" % (p.rel, x))
                status = 1
            elif not w["available"]:
                print("SKIP  %s: [[%s]] wiki not available locally (%s)" % (p.rel, x, w["path"]))
            else:
                cache.setdefault(wid, Wiki(w["path"]))
                target = cache[wid].page(slug.strip())
                if target:
                    print("OK    %s: [[%s]] -> %s" % (p.rel, x, posix(os.path.relpath(target.path, wiki.root))))
                else:
                    print("ERROR %s: [[%s]] page not found in %s" % (p.rel, x, w["path"]))
                    status = 1
    for prob in problems:
        print("ERROR %s" % prob)
    print("%d cross-wiki reference(s) checked" % count)
    return 1 if status or problems else 0


