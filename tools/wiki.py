ACCESS = {
    "read-only": {"claude": "Read, Glob, Grep, Bash", "copilot": ["read", "search", "execute"], "codex": "read-only"},
    "write": {"claude": "Read, Write, Edit, Glob, Grep, Bash",
              "copilot": ["read", "edit", "search", "execute", "todo"], "codex": "workspace-write"},
}
GENERATED_DIRS = (".claude/agents", ".claude/skills", ".github/agents", ".codex/agents")


def parse_agent(root, path):
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", read(path), re.S)
    if not m:
        sys.exit("error: %s has no frontmatter" % path)
    meta = {}
    for line in m.group(1).splitlines():
        key, _, value = line.partition(":")
        meta[key.strip()] = value.strip().strip("\"'")
    for field in ("name", "description", "access"):
        if not meta.get(field):
            sys.exit("error: %s: missing '%s'" % (path, field))
    if meta["access"] not in ACCESS:
        sys.exit("error: %s: access must be one of %s" % (path, ", ".join(ACCESS)))
    meta["body"] = m.group(2).strip() + "\n"
    meta["source"] = posix(os.path.relpath(path, root))
    if "'''" in meta["body"]:
        sys.exit("error: %s: body must not contain '''" % path)
    return meta


def render_agent_files(a):
    t = ACCESS[a["access"]]
    note = "<!-- %s sync from %s — edit the source and re-run. -->" % (GENERATED, a["source"])
    desc = json.dumps(a["description"], ensure_ascii=False)
    return {
        ".claude/agents/%s.md" % a["name"]:
            "---\nname: %s\ndescription: %s\ntools: %s\nmodel: inherit\n---\n%s\n\n%s" % (a["name"], desc, t["claude"], note, a["body"]),
        ".github/agents/%s.agent.md" % a["name"]:
            "---\nname: %s\ndescription: %s\ntools: %s\nuser-invocable: false\n---\n%s\n\n%s"
            % (a["name"], desc, json.dumps(t["copilot"]), note, a["body"]),
        ".codex/agents/%s.toml" % a["name"]:
            "# %s\nname = %s\ndescription = %s\nsandbox_mode = %s\ndeveloper_instructions = '''\n%s'''\n"
            % (note[5:-4], json.dumps(a["name"]), desc, json.dumps(t["codex"]), a["body"]),
    }


def sync_plan(root):
    """Return (expected {rel: bytes}, changed [rel], stale [rel])."""
    files = {}
    agents_dir = os.path.join(root, ".agents", "agents")
    if os.path.isdir(agents_dir):
        for fn in sorted(os.listdir(agents_dir)):
            if fn.endswith(".md") and fn != "README.md":
                for rel, text in render_agent_files(parse_agent(root, os.path.join(agents_dir, fn))).items():
                    files[rel] = text.encode("utf-8")
    skills = os.path.join(root, ".agents", "skills")
    for dirpath, dirnames, filenames in os.walk(skills):
        dirnames[:] = [d for d in dirnames if d != "__pycache__"]
        for fn in sorted(filenames):
            src = os.path.join(dirpath, fn)
            rel = posix(os.path.join(".claude", "skills", os.path.relpath(src, skills)))
            data = open(src, "rb").read()
            if fn == "SKILL.md":
                text = data.decode("utf-8")
                note = "<!-- %s sync from %s — edit the source and re-run. -->\n" % (GENERATED, posix(os.path.relpath(src, root)))
                m = re.match(r"^(---\n.*?\n---\n)(.*)$", text, re.S)
                data = ((m.group(1) + note + m.group(2)) if m else note + text).encode("utf-8")
            files[rel] = data
    changed = [rel for rel, data in sorted(files.items())
               if not os.path.exists(os.path.join(root, rel)) or open(os.path.join(root, rel), "rb").read() != data]
    stale = []
    for sub in GENERATED_DIRS:
        for dirpath, _, filenames in os.walk(os.path.join(root, sub)):
            for fn in filenames:
                rel = posix(os.path.relpath(os.path.join(dirpath, fn), root))
                if rel in files:
                    continue
                if rel.startswith(".claude/skills/") or "GENERATED by tools/" in read(os.path.join(dirpath, fn)):
                    stale.append(rel)
    return files, changed, sorted(stale)


def do_sync(root, check=False, quiet=False):
    files, changed, stale = sync_plan(root)
    if not check:
        for rel in changed:
            path = os.path.join(root, rel)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "wb") as f:
                f.write(files[rel])
        for rel in stale:
            os.remove(os.path.join(root, rel))
        skills = os.path.join(root, ".claude", "skills")
        for dirpath, dirnames, filenames in sorted(os.walk(skills), reverse=True):
            if dirpath != skills and not os.listdir(dirpath):
                os.rmdir(dirpath)
    for rel in changed:
        print(("OUTDATED " if check else "wrote    ") + rel)
    for rel in stale:
        print(("STALE    " if check else "removed  ") + rel)
    if check and (changed or stale):
        print("Generated agent files are out of date. Run: python3 tools/wiki.py sync")
        return 1
    if not quiet and not changed and not stale:
        print("agent files are up to date")
    return 0


def cmd_sync(wiki, args):
    return do_sync(wiki.root, args.check, args.quiet)


# --------------------------------------------------------------------------- framework: manifest, upgrade, new

def read_manifest(root):
    path = os.path.join(root, "tools", "framework-manifest.txt")
    return [l.strip() for l in read(path).splitlines() if l.strip() and not l.startswith("#")]


def framework_files(root):
    """Yield framework-managed file paths (posix, relative) present under root."""
    for entry in read_manifest(root):
        full = os.path.join(root, entry)
        if entry.endswith("/"):
            for dirpath, dirnames, filenames in os.walk(full):
                dirnames[:] = sorted(d for d in dirnames if d != "__pycache__")
                for fn in sorted(filenames):
                    if not fn.endswith(".pyc") and fn != "framework.lock":
                        yield posix(os.path.relpath(os.path.join(dirpath, fn), root))
        elif os.path.exists(full):
            yield entry


def copy_framework(src, dest, dry_run=False):
    added, updated = [], []
    for rel in framework_files(src):
        s, d = os.path.join(src, rel), os.path.join(dest, rel)
        data = open(s, "rb").read()
        if os.path.exists(d) and open(d, "rb").read() == data:
            continue
        (updated if os.path.exists(d) else added).append(rel)
        if not dry_run:
            os.makedirs(os.path.dirname(d) or ".", exist_ok=True)
            shutil.copyfile(s, d)
            if rel.startswith(".githooks/") or rel.endswith(".py"):
                os.chmod(d, 0o755)
    return added, updated


def enable_hooks(root):
    if os.path.isdir(os.path.join(root, ".git")) and os.path.isdir(os.path.join(root, ".githooks")):
        git(root, "config", "core.hooksPath", ".githooks")


def cmd_upgrade(wiki, args):
    fw = wiki.config.get("framework") or {}
    if wiki.config.get("template"):
        sys.exit("error: this is the template itself; upgrade is for wikis created from it")
    tmp = None
    try:
        if args.source:
            src = os.path.abspath(args.source)
            repo, commit = src, git(src, "rev-parse", "HEAD")
        else:
            repo = fw.get("repo") or DEFAULT_FRAMEWORK_REPO
            ref = args.ref or fw.get("ref") or "main"
            tmp = tempfile.mkdtemp(prefix="llm-wiki-")
            print("Fetching %s (%s)…" % (repo, ref))
            r = subprocess.run(["git", "clone", "-q", "--depth", "1", "--branch", ref, repo, tmp],
                               capture_output=True, text=True)
            if r.returncode != 0:
                sys.exit("error: could not clone framework: %s" % r.stderr.strip())
            src, commit = tmp, git(tmp, "rev-parse", "HEAD")
        added, updated = copy_framework(src, wiki.root, args.dry_run)
        upstream = set(framework_files(src))
        local_only = [f for f in framework_files(wiki.root) if f not in upstream]
    finally:
        if tmp:
            shutil.rmtree(tmp, ignore_errors=True)
    for rel in added:
        print("added    %s" % rel)
    for rel in updated:
        print("updated  %s" % rel)
    for rel in local_only:
        print("kept     %s (local only, not in framework)" % rel)
    if args.dry_run:
        print("\n(dry run) %d to add, %d to update" % (len(added), len(updated)))
        return 0
    write(os.path.join(wiki.root, ".agents", "framework.lock"), json.dumps(
        {"repo": repo, "commit": commit, "upgraded": today()}, indent=2) + "\n")
    script = os.path.join(wiki.root, "tools", "wiki.py")
    subprocess.run([sys.executable, script, "--root", wiki.root, "sync", "--quiet"], check=False)
    subprocess.run([sys.executable, script, "--root", wiki.root, "index", "--quiet"], check=False)
    enable_hooks(wiki.root)
    print("\nFramework upgraded: %d added, %d updated. Review with `git diff`, then commit "
          "(e.g. `upgrade: framework %s`)." % (len(added), len(updated), (commit or "")[:10]))
    if added or updated:
        log_args = argparse.Namespace(action=["add", "upgrade", "Framework %s" % (commit or "")[:10]],
                                      message=["%d files added, %d updated from %s" % (len(added), len(updated), repo)], n=10)
        cmd_log(Wiki(wiki.root), log_args)
    return 0


def ask(prompt, default=None, interactive=True):
    if not interactive:
        return default
    suffix = " [%s]" % default if default else ""
    value = input("%s%s: " % (prompt, suffix)).strip()
    return value or default


def yaml_list(items, indent=4):
    items = [i for i in items if i]
    if not items:
        return " " * indent + '- ""'
    return "\n".join(" " * indent + "- " + json.dumps(i, ensure_ascii=False) for i in items)


def render_skeleton(src, dest, values):
    skel = os.path.join(src, "templates", "skeleton")
    for dirpath, _, filenames in os.walk(skel):
        for fn in filenames:
            s = os.path.join(dirpath, fn)
            text = read(s)
            for k, v in values.items():
                text = text.replace("{{%s}}" % k, v)
            write(os.path.join(dest, os.path.relpath(s, skel)), text)
    for cat in DEFAULT_CATEGORIES:
        write(os.path.join(dest, "wiki", cat, ".gitkeep"), "")
    write(os.path.join(dest, "raw", "assets", ".gitkeep"), "")


def create_wiki(src, dest, args, in_place=False):
    interactive = sys.stdin.isatty() and not args.yes
    default_id = re.sub(r"[^a-z0-9]+", "-", os.path.basename(os.path.abspath(dest)).lower()).strip("-")
    default_id = re.sub(r"-?wiki$", "", default_id) or default_id
    wid = args.id or ask("Wiki id (kebab-case, unique)", default_id, interactive)
    if not wid or not SLUG_RE.match(wid):
        sys.exit("error: wiki id must be kebab-case (got %r)" % wid)
    name = args.name or ask("Wiki name", wid.replace("-", " ").title() + " Wiki", interactive)
    desc = args.description or ask("One-line description", "Knowledge base about %s." % name, interactive)
    scope_in = args.scope_in or [s.strip() for s in (ask("In scope (comma-separated)", "", interactive) or "").split(",")]
    scope_out = args.scope_out or [s.strip() for s in (ask("Out of scope (comma-separated)", "", interactive) or "").split(",")]
    src_cfg = load_config(src)
    values = {
        "ID": wid, "NAME": name, "DESCRIPTION": json.dumps(desc, ensure_ascii=False), "DATE": today(),
        "SCOPE_IN": yaml_list(scope_in), "SCOPE_OUT": yaml_list(scope_out),
        "FRAMEWORK_REPO": str((src_cfg.get("framework") or {}).get("repo") or DEFAULT_FRAMEWORK_REPO),
    }
    if not in_place:
        copy_framework(src, dest)
    else:
        for path in ("tests",):
            shutil.rmtree(os.path.join(dest, path), ignore_errors=True)
        for stale in ("wiki/_meta/external-links.md",):
            if os.path.exists(os.path.join(dest, stale)):
                os.remove(os.path.join(dest, stale))
    render_skeleton(src, dest, values)
    do_sync(dest, quiet=True)
    cmd_index(Wiki(dest), argparse.Namespace(check=False, quiet=True))
    if not args.no_git and shutil.which("git"):
        if not os.path.isdir(os.path.join(dest, ".git")):
            git(dest, "init", "-q", "-b", "main") is not None or git(dest, "init", "-q")
        enable_hooks(dest)
        git(dest, "add", "-A")
        subprocess.run(["git", "-C", dest, "commit", "-q", "--no-verify", "-m",
                        "setup: %s created from llm-wiki framework" % name], check=False)
    print("Created wiki '%s' (id: %s) in %s" % (name, wid, dest))
    if args.github:
        if not shutil.which("gh"):
            print("warning: GitHub CLI (gh) not found — create the repo manually and push.")
        else:
            vis = "--public" if args.public else "--private"
            r = subprocess.run(["gh", "repo", "create", args.github, vis, "--source", dest, "--push"])
            if r.returncode == 0:
                print("Pushed to GitHub: %s" % args.github)
    print("Next: open it with your agent (Copilot, Codex, Claude Code) and run setup-wiki, "
          "then drop sources into raw/ and run ingest.")
    return 0


def cmd_new(wiki, args):
    dest = os.path.abspath(args.target)
    if os.path.exists(dest) and os.listdir(dest):
        sys.exit("error: %s exists and is not empty" % dest)
    return create_wiki(wiki.root, dest, args)


def cmd_init(wiki, args):
    if not wiki.config.get("template"):
        sys.exit("error: this repo is already a wiki (wiki.config.yaml has no 'template: true')")
    return create_wiki(wiki.root, wiki.root, args, in_place=True)


